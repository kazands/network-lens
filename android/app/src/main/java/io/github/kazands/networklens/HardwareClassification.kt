package io.github.kazands.networklens

/** Physical type is independent of retail naming and service capabilities. No text guessing. */
internal object HardwareClassification {
    data class Fact(val category: DeviceCatalog.Category, val source: String)
    data class Result(val category: DeviceCatalog.Category?, val facts: List<Fact>, val conflicted: Boolean)
    // These APIs specifically describe lighting. Generic Cast, AirPlay, HTTP and
    // automation platforms deliberately have no physical category here.
    fun serviceKind(type: String): String = when (LocalServices.canonicalType(type)) {
        "_nanoleafapi._tcp." -> "Nanoleaf lighting device"
        "_wled._tcp." -> "WLED lighting controller"
        else -> ""
    }

    fun capabilities(services: Collection<String>): List<String> = services.mapNotNull { service ->
        when (LocalServices.canonicalType(service)) {
            "_airplay._tcp." -> "AirPlay"
            "_raop._tcp." -> "AirPlay audio (RAOP)"
            "_spotify-connect._tcp." -> "Spotify Connect"
            "_googlecast._tcp." -> "Google Cast"
            FireTvInfo.TYPE -> "Amazon WhisperPlay"
            SmartThingsInfo.TYPE, SmartThingsInfo.HEDGE_TYPE -> "SmartThings"
            "_androidtvremote2._tcp." -> "Android TV remote service"
            "_ipp._tcp.", "_ipps._tcp.", "_printer._tcp.", "_pdl-datastream._tcp." -> "Printing"
            "_uscan._tcp.", "_uscans._tcp." -> "Document scanning"
            "_smb._tcp." -> "File sharing"
            "_hap._tcp.", "_hap._udp." -> "HomeKit"
            "_matter._tcp.", "_matterc._udp." -> "Matter"
            "_meshcop._udp." -> "Thread border router"
            "_companion-link._tcp." -> "Apple Companion Link"
            else -> when (service) {
                "urn:schemas-upnp-org:device:MediaRenderer:1" -> "DLNA media playback"
                AppleDeviceInfo.SERVICE -> AppleDeviceInfo.SERVICE
                "Cast speaker group" -> "Cast speaker group"
                else -> null
            }
        }
    }.distinct().sorted()

    // Exact protocol labels generated by our parsers, never arbitrary substring matching.
    fun reported(kind: String): DeviceCatalog.Category? = when (kind) {
        "HomeKit thermostat" -> DeviceCatalog.Category.THERMOSTAT
        "HomeKit television", "Samsung television" -> DeviceCatalog.Category.TV
        "HomeKit TV media player" -> DeviceCatalog.Category.TV_PLAYER
        "Yamaha soundbar", "Yamaha subwoofer", "HomeKit speaker" -> DeviceCatalog.Category.SPEAKER
        "HomeKit audio receiver", "Yamaha audio receiver" -> DeviceCatalog.Category.AUDIO_RECEIVER
        "HomeKit light", "UPnP light", "Yeelight light", "Nanoleaf lighting device", "WLED lighting controller" -> DeviceCatalog.Category.LIGHT
        "HomeKit lock" -> DeviceCatalog.Category.LOCK
        "HomeKit outlet" -> DeviceCatalog.Category.OUTLET
        "HomeKit switch" -> DeviceCatalog.Category.SWITCH
        "HomeKit sensor" -> DeviceCatalog.Category.SENSOR
        "HomeKit fan" -> DeviceCatalog.Category.FAN
        "HomeKit heater" -> DeviceCatalog.Category.HEATER
        "HomeKit air conditioner" -> DeviceCatalog.Category.AIR_CONDITIONER
        "HomeKit air purifier" -> DeviceCatalog.Category.AIR_PURIFIER
        "HomeKit humidifier" -> DeviceCatalog.Category.HUMIDIFIER
        "HomeKit dehumidifier" -> DeviceCatalog.Category.DEHUMIDIFIER
        "HomeKit video doorbell" -> DeviceCatalog.Category.DOORBELL
        "HomeKit camera", "UPnP camera", "Video surveillance device", "Network surveillance device" -> DeviceCatalog.Category.CAMERA
        "HomeKit bridge", "Discovery smart-home bridge" -> DeviceCatalog.Category.BRIDGE
        "HomeKit garage door" -> DeviceCatalog.Category.GARAGE_DOOR
        "HomeKit security system" -> DeviceCatalog.Category.SECURITY_SYSTEM
        "HomeKit door" -> DeviceCatalog.Category.DOOR
        "HomeKit window" -> DeviceCatalog.Category.WINDOW
        "HomeKit window covering" -> DeviceCatalog.Category.WINDOW_COVERING
        "Omada access point", "TP-Link EAP access point" -> DeviceCatalog.Category.ACCESS_POINT
        "Omada network switch", "TP-Link Easy Smart network switch" -> DeviceCatalog.Category.NETWORK_SWITCH
        "Omada gateway" -> DeviceCatalog.Category.ROUTER
        "HomeKit router service" -> DeviceCatalog.Category.ROUTER
        "HomeKit range extender" -> DeviceCatalog.Category.RANGE_EXTENDER
        "HomeKit sprinkler" -> DeviceCatalog.Category.SPRINKLER
        "HomeKit faucet" -> DeviceCatalog.Category.FAUCET
        "HomeKit shower" -> DeviceCatalog.Category.SHOWER
        "HomeKit remote" -> DeviceCatalog.Category.REMOTE
        else -> null
    }

    /** Retain every distinct category even after bounded display observations are evicted. */
    class Evidence {
        private val facts = linkedMapOf<DeviceCatalog.Category, java.util.TreeSet<String>>()
        fun offer(kind: String, source: String) {
            val category = reported(kind) ?: return
            offerCategory(category, source)
        }
        fun offerCategory(category: DeviceCatalog.Category, source: String) {
            if (category == DeviceCatalog.Category.UNSPECIFIED || source.isEmpty()) return
            val sources = facts.getOrPut(category) { java.util.TreeSet() }
            sources.add(SafeText.label(source, 128))
            if (sources.size > 4) sources.pollLast()
        }
        fun snapshot(): List<Fact> = facts.flatMap { (category, sources) -> sources.map { Fact(category, it) } }
        fun copy() = Evidence().also { other -> facts.forEach { (category, sources) -> other.facts[category] = java.util.TreeSet(sources) } }
    }

    fun resolve(facts: List<Fact>): Result {
        val types = facts.map { it.category }.filter { it != DeviceCatalog.Category.UNSPECIFIED }.toMutableSet()
        // A recorder or doorbell is a refinement of the broad camera/surveillance role.
        if (DeviceCatalog.Category.RECORDER in types || DeviceCatalog.Category.DOORBELL in types) types.remove(DeviceCatalog.Category.CAMERA)
        // A hub can also advertise a bridge role.
        if (DeviceCatalog.Category.HUB in types) types.remove(DeviceCatalog.Category.BRIDGE)
        if (DeviceCatalog.Category.REMOTE_HUB in types) types.remove(DeviceCatalog.Category.REMOTE)
        val ordered = facts.distinct().sortedWith(compareBy({ it.category.name }, { it.source }))
        return Result(types.singleOrNull(), ordered, types.size > 1)
    }
}
