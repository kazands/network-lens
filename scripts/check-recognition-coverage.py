#!/usr/bin/env python3
"""Offline policy gate: every pinned integration has an explicit interpretation decision."""
import argparse, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'android/app/src/main/java/io/github/kazands/networklens'
def render():
    rules = re.findall(r'Rule\("([^"]+)", "([^"]+)"', (BASE/'HaMatchers.kt').read_text())
    domains = {domain for _, domain in rules}
    profiles = dict(re.findall(r'"([a-z0-9_]+)" to Family\("([^"]+)"', (BASE/'DiscoveryMatchers.kt').read_text()))
    policy = json.loads((ROOT/'android/recognition-coverage.json').read_text())
    assert set(policy) == domains, f'Coverage decisions missing/stale: {sorted(set(policy)^domains)}'
    lines = ['# Recognition family coverage', '',
        'Generated by `scripts/check-recognition-coverage.py --write`. This is a policy inventory, not a device-accuracy score.', '',
        'All entries use the pinned Home Assistant matcher provenance in `android/ha-matcher-provenance.json`. A match identifies an integration candidate; it does not verify an exact product or manufacturer. HomeKit model-only matches remain technical candidates.', '',
        'Family labels preserve useful reported names. Exact model readers and catalogues operate separately. A deferred interpretation still retains current service evidence.', '',
        '| Integration | Discovery inputs | Interpretation | Limit |', '|---|---|---|---|']
    for domain in sorted(domains):
        item=policy[domain]
        assert item['policy'] in ('family','evidence-only') and len(item['reason']) > 20
        assert (domain in profiles) == (item['policy']=='family'), f'Profile decision drift: {domain}'
        kinds=', '.join(sorted({kind for kind,d in rules if d==domain}))
        label=profiles.get(domain,'Evidence only; product interpretation deferred')
        lines.append(f"| {domain} | {kinds} | {label} | {item['reason']} |")
    lines += ['', f'{len(domains)} integration policies; {len(domains & profiles.keys())} family labels; {len(domains - profiles.keys())} explicit deferrals.', '',
        'Active readers not sourced from these integration rules include Apple device information, TP-Link/Omada/Easy Smart, PlayStation, Envisalink, Ubiquiti/MikroTik, eSCL, SADP and WS-Discovery. See DISCOVERY-COVERAGE.md and NETWORK-EQUIPMENT.md.', '']
    return '\n'.join(lines)
if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    output=ROOT/'docs/reference/RECOGNITION-COVERAGE.md';expected=render()
    if args.write: output.write_text(expected)
    else: assert output.read_text()==expected, 'Recognition coverage document is stale; review policy and run --write'
    print('PASS: every integration has a checked recognition policy')
