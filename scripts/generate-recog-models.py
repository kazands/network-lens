#!/usr/bin/env python3
"""Generate exact model lookups from a pinned, retained Recog dataset. No network I/O."""
import argparse
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
REVISION = 'f1191e24332c51d6a3d98457f64fba8dec340784'
SOURCE = ROOT / 'android/recog-original/mdns_device-info_txt.xml'
DESTINATION = ROOT / 'android/app/src/main/java/io/github/kazands/networklens/RecogModels.kt'
PROVENANCE = ROOT / 'android/recog-provenance.json'
SOURCE_BLOB = '4499b9c787784baebf70864d373e362f5e1ac295'
LICENSE_BLOB = 'ad5b8d9acc33da2a18a9187a8374f6ef501a5443'
CANONICAL = re.compile(r'(?:MacBook(?:Air|Pro)?|Macmini|MacPro|iMac(?:Pro)?|iPad|iPhone|iPod|AppleTV|AudioAccessory)\d+,\d+')
# Upstream gives these two identifiers the same 27-inch description; the first
# generation also includes 21.5-inch hardware. Do not publish that specific guess.
EXCLUDED = {'iMac10,1', 'iMac11,1'}
CATEGORIES = {'Laptop': 'LAPTOP', 'Desktop': 'DESKTOP', 'Tablet': 'TABLET',
              'Mobile Phone': 'PHONE', 'Media Player': 'HANDHELD'}


def blob(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()


def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')


def generate():
    data = SOURCE.read_bytes()
    assert blob(data) == SOURCE_BLOB, 'Retained Recog source differs from the pinned blob'
    license_data = (SOURCE.parent / 'COPYING').read_bytes()
    assert blob(license_data) == LICENSE_BLOB, 'Retained Recog license differs from upstream'
    assert (ROOT / 'android/app/src/main/res/raw/recog_license.txt').read_bytes() == license_data
    root = ET.fromstring(data)
    assert root.get('matches') == 'mdns.device-info.txt'
    rows = {}
    for number, fingerprint in enumerate(root.findall('fingerprint'), 1):
        pattern = fingerprint.get('pattern', '')
        if not pattern.startswith('^model=') or not pattern.endswith('$'):
            continue
        params = {p.get('name'): p.get('value') for p in fingerprint.findall('param') if p.get('pos') == '0'}
        if params.get('hw.vendor') != 'Apple':
            continue
        category = CATEGORIES.get(params.get('hw.device'))
        if params.get('hw.family') == 'HomePod':
            category = 'SPEAKER'
        elif params.get('hw.family') == 'Apple TV':
            category = 'TV_PLAYER'
        if category is None:
            continue
        product = params.get('hw.product', '')
        # Low-certainty Apple TV rules justify only the product family and icon.
        # Preserve the upstream marker in provenance; do not invent a percentage.
        family_only = 'hw.certainty' in params
        if family_only:
            assert params.get('hw.family') == 'Apple TV'
            product = 'Apple TV'
        assert product and len(product) <= 160 and '{' not in product
        for example in fingerprint.findall('example'):
            value = example.text or ''
            if not value.startswith('model='):
                continue
            code = value[6:]
            if not CANONICAL.fullmatch(code) or code in EXCLUDED:
                continue
            assert re.fullmatch(pattern, value), f'Upstream example fails its own rule: {code}'
            row = {'code': code, 'description': product, 'category': category,
                   'rule': number, 'family_only': family_only}
            assert code not in rows or rows[code] == row, f'Ambiguous upstream example: {code}'
            rows[code] = row
    assert len(rows) == 156, 'Review coverage changes before updating the generated table'
    lines = ['// Generated by scripts/generate-recog-models.py; do not edit.',
             '// Derived from Rapid7 Recog, Copyright (c) 2014-2015, Rapid7; BSD-2-Clause.',
             '// Full terms: res/raw/recog_license.txt and android/recog-original/COPYING.',
             'package io.github.kazands.networklens', '', 'internal object RecogModels {',
             f'    const val REVISION = "{REVISION}"',
             '    fun lookup(code: String): Recog.Model? = when (code) {']
    for code, row in sorted(rows.items()):
        lines.append(f'        {literal(code)} -> Recog.Model(code, {literal(row["description"])}, Recog.Category.{row["category"]}, {row["rule"]}, {str(row["family_only"]).lower()})')
    lines += ['        else -> null', '    }', '}', '']
    output = '\n'.join(lines)
    provenance = {'repository': 'rapid7/recog', 'revision': REVISION, 'license': 'BSD-2-Clause',
                  'source_path': 'xml/mdns_device-info_txt.xml', 'source_git_blob_sha': SOURCE_BLOB,
                  'source_sha256': hashlib.sha256(data).hexdigest(), 'license_git_blob_sha': LICENSE_BLOB,
                  'policy': 'Exact canonical model examples from anchored hardware rules only; no runtime regex, board IDs, prefix inference or OS rules.',
                  'excluded_codes': sorted(EXCLUDED), 'family_only_codes': sorted(code for code, r in rows.items() if r['family_only']),
                  'models': len(rows), 'generated_sha256': hashlib.sha256(output.encode()).hexdigest()}
    return output, json.dumps(provenance, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify committed output without changing files')
    args = parser.parse_args()
    code, provenance = generate()
    for path, content in [(DESTINATION, code), (PROVENANCE, provenance)]:
        if args.check:
            assert path.read_text() == content, f'Stale generated Recog output: {path.relative_to(ROOT)}'
        else:
            path.write_text(content)
    print('Verified 156 exact offline Recog model mappings.' if args.check else 'Generated 156 exact offline Recog model mappings.')


if __name__ == '__main__':
    main()
