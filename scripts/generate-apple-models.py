#!/usr/bin/env python3
"""Generate reviewed, exact supplemental mobile model mappings. No network I/O."""
import argparse
import hashlib
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'android/appledb-original/device-main.json'
SOURCE_BLOB = '22e79f5e8fa7cb79a53b7509450fec614dbc5877'
LICENSE_BLOB = '11a08f9af7d8af49a9977c9da8a1352fc87d95a3'
REVIEW_DATE = date(2026, 11, 15)
DESTINATION = ROOT / 'android/app/src/main/java/io/github/kazands/networklens/AppleModels.kt'
PROVENANCE = ROOT / 'android/apple-model-provenance.json'
TYPES = {'iPhone': 'PHONE', 'iPad': 'TABLET', 'iPad mini': 'TABLET',
         'iPad Air': 'TABLET', 'iPad Pro': 'TABLET'}


def blob(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()


def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')


def select_boards(source_entries, eligible, known_codes):
    # Board IDs are admitted only when the entire retained source has one owner
    # and that released mobile owner has exactly one canonical ProductType.
    owners = {}
    for entry in source_entries:
        for board in entry.get('board', []):
            owners.setdefault(board, []).append(entry)
    boards, excluded = {}, []
    for entry in eligible:
        for board in entry.get('board', []):
            if len(owners[board]) != 1 or len(entry['identifier']) != 1:
                excluded.append({'key': board, 'reason': 'board has multiple owners or ProductTypes'})
                continue
            assert re.fullmatch(r'[A-Z][A-Za-z0-9]*AP', board), board
            code = entry['identifier'][0]
            assert code in known_codes
            boards[board] = code
    return boards, excluded


def generate():
    data = SOURCE.read_bytes()
    assert blob(data) == SOURCE_BLOB, 'AppleDB source differs from the reviewed blob'
    terms = (SOURCE.parent / 'LICENSE').read_bytes()
    assert blob(terms) == LICENSE_BLOB, 'AppleDB license differs from the reviewed blob'
    assert (ROOT / 'android/app/src/main/res/raw/appledb_license.txt').read_bytes() == terms
    # Keep all existing conservative Recog interpretations, including shared models.
    existing = set(re.findall(r'^        "([^"]+)" ->',
        (DESTINATION.parent / 'RecogModels.kt').read_text(), re.M))
    selected, excluded, eligible = {}, [], []
    source_entries = json.loads(data)
    for entry in source_entries:
        if entry['type'] not in TYPES:
            continue
        releases = entry.get('released', [])
        if isinstance(releases, str):
            releases = [releases]
        if entry.get('internal') or not releases or not any(date.fromisoformat(d) <= REVIEW_DATE for d in releases):
            excluded.append({'key': entry['key'], 'reason': 'internal or not released by review date'})
            continue
        eligible.append(entry)
        title = entry['name']
        assert 1 <= len(title) <= 160 and all(ord(c) >= 32 for c in title)
        for code in entry['identifier']:
            assert re.fullmatch(r'(?:iPad|iPhone)[0-9]+,[0-9]+', code), code
            assert code.startswith('iPhone') == (entry['type'] == 'iPhone')
            if code in existing:
                excluded.append({'key': code, 'reason': 'existing reviewed Recog mapping retained'})
                continue
            row = {'code': code, 'title': title, 'category': TYPES[entry['type']], 'key': entry['key']}
            assert code not in selected or selected[code] == row, 'Ambiguous identifier: ' + code
            selected[code] = row
    assert selected['iPad13,18']['title'] == 'iPad (10th generation) Wi-Fi'
    assert selected['iPad13,19']['title'] == 'iPad (10th generation) Wi-Fi + Cellular'
    boards, board_exclusions = select_boards(source_entries, eligible, existing | selected.keys())
    excluded.extend(board_exclusions)
    rows = [selected[code] for code in sorted(selected)]
    lines = ['// Generated by scripts/generate-apple-models.py; do not edit.',
             '// AppleDB data: MIT, Copyright (c) 2022 emiyl.',
             '// Full notice: res/raw/appledb_license.txt; retained source: android/appledb-original/.',
             'package io.github.kazands.networklens', '', 'internal object AppleModels {',
             f'    const val SOURCE_BLOB = "{SOURCE_BLOB}"',
             '    fun lookup(code: String): Recog.Model? = when (code) {']
    for row in rows:
        lines.append(f'        {literal(row["code"])} -> Recog.Model(code, {literal(row["title"])}, '
                     f'Recog.Category.{row["category"]}, 0, false, catalogueSource = "AppleDB · $SOURCE_BLOB")')
    lines.extend(['        else -> boards[code]?.let { canonical -> Recog.lookup(canonical)?.copy(',
                  '            code = code, catalogueSource = "AppleDB · $SOURCE_BLOB") }', '    }',
                  '    private val boards = mapOf('])
    lines.extend(f'        {literal(board)} to {literal(code)},' for board, code in sorted(boards.items()))
    lines.extend(['    )', '    private val aliases = boards.entries.groupBy({ it.value }, { it.key })',
                  '    fun canonicalCode(code: String): String = boards[code] ?: code',
                  '    fun aliases(code: String): Set<String> = canonicalCode(code).let { setOf(it) + aliases[it].orEmpty() }',
                  '}', ''])
    generated = '\n'.join(lines)
    provenance = {'source': 'https://github.com/littlebyteorg/appledb/blob/gh-pages/device/main.json',
                  'sourceGitBlob': SOURCE_BLOB, 'sourceSha256': hashlib.sha256(data).hexdigest(),
                  'licenseGitBlob': LICENSE_BLOB, 'reviewDate': str(REVIEW_DATE),
                  'policy': 'Exact released iPad/iPhone identifiers and globally unique boards with one ProductType; no prefix or retail model-number guessing; existing Recog mappings retained; ambiguous boards excluded and ambiguous identifiers fail generation.',
                  'references': ['https://support.apple.com/en-us/108043',
                                 'https://support.apple.com/en-us/111840'],
                  'count': len(rows), 'mappings': rows, 'boardAliasCount': len(boards),
                  'boardAliases': dict(sorted(boards.items())), 'exclusions': excluded,
                  'generatedSha256': hashlib.sha256(generated.encode()).hexdigest()}
    return generated, json.dumps(provenance, indent=2, ensure_ascii=False) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, provenance = generate()
    for path, expected in [(DESTINATION, generated), (PROVENANCE, provenance)]:
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit('Stale Apple model output: ' + str(path.relative_to(ROOT)))
        else:
            path.write_text(expected)
    print('PASS · reviewed supplemental Apple mobile mappings:', json.loads(provenance)['count'])
